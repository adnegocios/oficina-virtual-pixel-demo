// Quita tildes y pasa a mayúsculas: "Tesorería" → "TESORERIA"
function normalizar(texto) {
  return String(texto).normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

/** Ancho en píxeles que ocupará el texto. */
export function anchoTexto(texto) {
  let ancho = 0;
  for (const c of normalizar(texto)) ancho += (G[c] || G['?'])[0].length + 1;
  return Math.max(0, ancho - 1);
}

/** Dibuja texto en coordenadas lógicas (x, y = esquina superior izquierda). */
export function dibujarTexto(g, texto, x, y, color) {
  g.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const c of normalizar(texto)) {
    const glifo = G[c] || G['?'];
    for (let fila = 0; fila < glifo.length; fila++) {
      const linea = glifo[fila];
      for (let col = 0; col < linea.length; col++) {
        if (linea[col] === '#') g.fillRect(cx + col, cy + fila, 1, 1);
      }
    }
    cx += glifo[0].length + 1;
  }
}
